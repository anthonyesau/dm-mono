# ------------------------------------------------------------------- access

def has(name):
    return name in G


def ref(name, a=1, b=0, c=0, d=1, e=0, f=0):
    """Reuse another skeleton, transformed."""
    return ("ref", name, (a, b, c, d, e, f))


def draw(name, pen):
    for item in G[name]:
        if isinstance(item, tuple):
            _, other, t = item
            draw(other, TransformPen(pen, t))
        else:
            parse_path(item, pen)


def recording(name):
    """RecordingPen value with the glyph's open and closed subpaths."""
    pen = RecordingPen()
    draw(name, pen)
    return pen.value


def subpaths(value):
    """Split a recording into [(closed, [(op, args)...])] lists."""
    out, cur = [], None
    for op, args in value:
        if op == "moveTo":
            cur = [(op, args)]
        elif op in ("closePath", "endPath"):
            out.append((op == "closePath", cur))
            cur = None
        else:
            cur.append((op, args))
    if cur:
        out.append((False, cur))
    return out


def flatten(value, steps=12):
    polys = []
    for closed, segs in subpaths(value):
        pts = [segs[0][1][0]]
        for op, args in segs[1:]:
            if op == "lineTo":
                pts.append(args[0])
            elif op == "curveTo":
                p0, (p1, p2, p3) = pts[-1], args
                for i in range(1, steps + 1):
                    t = i / steps
                    mt = 1 - t
                    pts.append((mt ** 3 * p0[0] + 3 * mt * mt * t * p1[0] + 3 * mt * t * t * p2[0] + t ** 3 * p3[0],
                                mt ** 3 * p0[1] + 3 * mt * mt * t * p1[1] + 3 * mt * t * t * p2[1] + t ** 3 * p3[1]))
            elif op == "qCurveTo":
                pts.extend(args)
        if closed:
            pts.append(pts[0])
        polys.append(pts)
    return polys


def polylines(name):
    return flatten(recording(name))
