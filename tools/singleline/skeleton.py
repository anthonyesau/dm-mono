K = 0.6  # handle ratio of DM Mono's superelliptic rounds


def oval(cx, cy, rx, ry, k=K):
    hx, hy = rx * k, ry * k
    return (f"M{cx} {cy - ry} C{cx + hx} {cy - ry} {cx + rx} {cy - hy} {cx + rx} {cy} "
            f"C{cx + rx} {cy + hy} {cx + hx} {cy + ry} {cx} {cy + ry} "
            f"C{cx - hx} {cy + ry} {cx - rx} {cy + hy} {cx - rx} {cy} "
            f"C{cx - rx} {cy - hy} {cx - hx} {cy - ry} {cx} {cy - ry} Z")


def circle(cx, cy, r):
    return oval(cx, cy, r, r, 0.5523)


