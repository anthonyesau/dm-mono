"""Add the technical-symbol extension to the DM Mono .glyphs sources.

usage: python build.py [source.glyphs ...]
Defaults to both masters files in ../../source. The script is idempotent: it
replaces any glyphs it generated before.
"""

import os
import sys

import glyphsLib
from glyphsLib.classes import GSComponent, GSGlyph, GSLayer, GSNode, GSPath

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import geo  # noqa: E402
from fontsrc import contours  # noqa: E402
from recipes import DIGITS, FRACTIONS, RECIPES, SUPERIOR_NAMES, SYM_SUPS, Ctx  # noqa: E402

SOURCES = [os.path.join(HERE, "..", "..", "source", n)
           for n in ("DMMono-MASTER.glyphs", "DMMono-Italics-MASTER.glyphs")]

# Stroke and scaling parameters per weight master. `sup` and `frac` were fitted
# so the generated figures overlay the designer's own ¹²³⁴ and ½¼¾ figures.
PARAMS = {
    "Light": dict(t=64, ring_t=54, sup=(0.579, 8.7, 7.5), frac=(0.36, 17.9, 15.0),
                  narrow=(0.235, 0.28, 11.5, 11.0)),
    "Medium": dict(t=96, ring_t=74, sup=(0.572, 11.7, 9.8), frac=(0.359, 18.5, 15.4),
                   narrow=(0.235, 0.28, 13.0, 11.5)),
}

GENERATED_NOTE = "Generated by tools/extend/build.py"
VERSION = (1, 100)  # 1.100: technical-symbol extension


def weight_of(master):
    return "Light" if "Light" in master.name else "Medium"


def to_path(contour, italic):
    if italic:
        contour = geo.slant([contour])[0]
    p = GSPath()
    p.closed = True
    p.nodes = [GSNode((x, y), typ) for x, y, typ in contour.to_nodes()]
    return p


def build_font(path):
    font = glyphsLib.GSFont(path)
    italic = any(m.italicAngle for m in font.masters)
    new_names = [r[0] for r in RECIPES]

    # drop glyphs from an earlier run (and complain about real clashes)
    for name, uni, _ in RECIPES:
        g = font.glyphs[name]
        if g is not None:
            if g.note != GENERATED_NOTE:
                raise SystemExit(f"{name} already exists in {path} and was not generated")
            del font.glyphs[name]
        if uni is not None:
            for g in font.glyphs:
                if g.unicode and int(g.unicode, 16) == uni:
                    raise SystemExit(f"U+{uni:04X} already encoded as {g.name}")

    ctxs = {}
    for m in font.masters:
        prm = PARAMS[weight_of(m)]

        def src(name, paths=None, _mid=m.id):
            return contours(font, name, _mid, italic=italic, paths=paths)

        ctxs[m.id] = Ctx(font=font, master_id=m.id, master_name=weight_of(m), italic=italic,
                         src=src, **prm)

    for name, uni, fn in RECIPES:
        g = GSGlyph(name)
        if uni is not None:
            g.unicode = "%04X" % uni
        g.note = GENERATED_NOTE
        font.glyphs.append(g)
        for m in font.masters:
            shape = fn(ctxs[m.id])
            layer = GSLayer()
            layer.layerId = m.id
            layer.associatedMasterId = m.id
            layer.width = 600
            g.layers.append(layer)
            for c in shape.contours:
                layer.paths.append(to_path(c, italic))
            for cname, dx, dy in shape.components:
                if italic:
                    dx += dy * geo.ITALIC_TAN
                layer.components.append(GSComponent(cname, offset=(round(dx), round(dy))))

    check_compatibility(font, new_names)
    update_features(font)
    update_parameters(font)
    font.save(path)
    print(f"{os.path.basename(path)}: added {len(RECIPES)} glyphs")


def check_compatibility(font, names):
    for name in names:
        g = font.glyphs[name]
        sigs = []
        for layer in g.layers:
            sig = ([tuple(n.type for n in p.nodes) for p in layer.paths],
                   [c.name for c in layer.components])
            sigs.append(sig)
        if any(s != sigs[0] for s in sigs[1:]):
            raise SystemExit(f"{name}: masters are not compatible")


# ------------------------------------------------------------------ features

def cls(*names):
    return "[" + " ".join(names) + "]"


def feature_code():
    figures = cls(*DIGITS)
    numr_names = [d + ".numr" for d in DIGITS]
    dnom_names = [d + ".dnom" for d in DIGITS]
    numr, dnom = cls(*numr_names), cls(*dnom_names)
    numr_ctx = cls("fraction.diag", *numr_names)
    dnom_ctx = cls("fraction.diag", *dnom_names)
    sups = [(d, SUPERIOR_NAMES[d]) for d in DIGITS] + [(s, b + "superior") for b, _, s, _ in SYM_SUPS]
    sups.append(("hyphen", "minussuperior"))
    infs = [(d, d + "inferior") for d in DIGITS] + [(s, b + "inferior") for b, _, s, _ in SYM_SUPS]
    infs.append(("hyphen", "minusinferior"))

    code = {}
    code["sups"] = "\n".join(f"sub {a} by {b};" for a, b in sups)
    code["subs"] = "\n".join(f"sub {a} by {b};" for a, b in infs)
    code["sinf"] = code["subs"]
    code["numr"] = f"sub {figures} by {numr};"
    code["dnom"] = f"sub {figures} by {dnom};"

    lines = []
    lines.append("# Turn a slash between figures into a fraction slash,")
    lines.append("# but leave dates such as 12/31/2020 alone.")
    lines.append("lookup FracSlash {")
    for n in range(1, 5):
        figs = " ".join([figures] * n)
        lines.append(f"\tignore sub [slash fraction] {figs} [slash fraction]';")
        lines.append(f"\tignore sub [slash fraction]' {figs} [slash fraction];")
    lines.append(f"\tsub {figures} [slash fraction]' {figures} by fraction.diag;")
    lines.append("} FracSlash;")
    lines.append("lookup FracNumerator {")
    lines.append(f"\trsub {figures}' {numr_ctx} by {numr};")
    lines.append("} FracNumerator;")
    lines.append("lookup FracDenominator {")
    lines.append(f"\tsub {dnom_ctx} {figures}' by {dnom};")
    lines.append("} FracDenominator;")
    lines.append("# Single-figure fractions that have a stacked Unicode glyph.")
    lines.append("lookup FracPrecomposed {")
    lines.append(f"\tignore sub {numr} {numr}' fraction.diag {dnom};")
    lines.append(f"\tignore sub {numr}' fraction.diag {dnom} {dnom};")
    precomposed = [("onehalf", "one", "two"), ("onequarter", "one", "four"),
                   ("threequarters", "three", "four")]
    precomposed += [(n, a, b) for n, _, a, b in FRACTIONS]
    for name, a, b in precomposed:
        lines.append(f"\tsub {a}.numr' fraction.diag' {b}.dnom' by {name};")
    lines.append("} FracPrecomposed;")
    lines.append("# 1/10 has a stacked glyph too")
    lines.append("lookup FracTenth {")
    lines.append(f"\tignore sub {numr} one.numr' fraction.diag one.dnom zero.dnom;")
    lines.append(f"\tignore sub one.numr' fraction.diag one.dnom zero.dnom {dnom};")
    lines.append("\tsub one.numr' fraction.diag' one.dnom' zero.dnom' by onetenth;")
    lines.append("} FracTenth;")
    code["frac"] = "\n".join(lines)
    return code


def update_features(font):
    code = feature_code()
    order = [f.name for f in font.features]
    for name, body in code.items():
        feat = next((f for f in font.features if f.name == name), None)
        if feat is None:
            from glyphsLib.classes import GSFeature
            feat = GSFeature(name, body)
            # keep new features next to their relatives
            anchor = "frac" if name in ("numr", "dnom") else "sups"
            idx = order.index(anchor) + 1
            font.features.insert(idx, feat)
            order.insert(idx, name)
        feat.code = body
        feat.automatic = False
    aalt = next(f for f in font.features if f.name == "aalt")
    wanted = ["locl", "subs", "sinf", "sups", "numr", "dnom", "frac", "ordn", "salt",
              "ss01", "ss02", "ss03", "ss04", "ss05"]
    aalt.code = "".join(f"feature {n};\n" for n in wanted)
    aalt.automatic = False


def update_parameters(font):
    font.versionMajor, font.versionMinor = VERSION
    # Let the compiler derive the OS/2 Unicode ranges from the new cmap.
    for i, p in reversed(list(enumerate(font.customParameters))):
        if p.name == "unicodeRanges":
            del font.customParameters[i]


if __name__ == "__main__":
    for p in sys.argv[1:] or SOURCES:
        build_font(os.path.abspath(p))
